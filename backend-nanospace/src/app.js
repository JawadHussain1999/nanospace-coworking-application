const express=require('express');
const cors=require('cors');
const helmet=require('helmet');
const rateLimit=require('express-rate-limit');
const {authenticate}=require('./middleware/auth');
const {notFound,errorHandler}=require('./middleware/errors');
const app=express();
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({origin:process.env.CORS_ORIGIN?process.env.CORS_ORIGIN.split(',').map(x=>x.trim()):true}));
app.use(express.json({limit:'10mb'}));
app.use(express.urlencoded({extended:false,limit:'10mb'}));
app.use('/api/auth/login',rateLimit({windowMs:15*60*1000,limit:20,standardHeaders:true,legacyHeaders:false}));
app.post('/api/auth/signup',rateLimit({windowMs:15*60*1000,limit:5,standardHeaders:true,legacyHeaders:false}));
app.use('/api/auth/forgot-password',rateLimit({windowMs:15*60*1000,limit:5,standardHeaders:true,legacyHeaders:false}));
app.use('/api/auth/reset-password',rateLimit({windowMs:15*60*1000,limit:10,standardHeaders:true,legacyHeaders:false}));
app.get('/api/health',(req,res)=>res.json({status:'ok',service:'nanospace-api',timestamp:new Date().toISOString()}));
app.use('/api/auth',require('./routes/auth.routes'));
app.use('/api',authenticate);
app.use('/api/branches',require('./routes/branches.routes'));
app.use('/api/users',require('./routes/users.routes'));
app.use('/api/customers',require('./routes/customers.routes'));
app.use('/api/inventory',require('./routes/inventory.routes'));
app.use('/api/workspaces',require('./routes/workspaces.routes'));
app.use('/api/bookings',require('./routes/bookings.routes'));
app.use('/api/quotations',require('./routes/quotations.routes'));
app.use('/api/complaints',require('./routes/complaints.routes'));
app.use('/api/notifications',require('./routes/notifications.routes'));
app.use('/api/dashboard',require('./routes/dashboard.routes'));
app.use('/api/attendance',require('./routes/attendance.routes'));
app.use('/api/leaves',require('./routes/leaves.routes'));
app.use('/api/payroll',require('./routes/payroll.routes'));
app.use('/api/agreements',require('./routes/agreements.routes'));
app.use('/api/payments',require('./routes/payments.routes'));
app.use('/api/invoices',require('./routes/invoices.routes'));
app.use('/api/expenses',require('./routes/expenses.routes'));
app.use('/api/reports',require('./routes/reports.routes'));
app.use('/api/settings',require('./routes/settings.routes'));
app.use('/api/documents',require('./routes/documents.routes'));
app.use('/api/audit-logs',require('./routes/auditLogs.routes'));
app.use(notFound);
app.use(errorHandler);
module.exports=app;
