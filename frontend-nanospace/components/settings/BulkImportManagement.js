async function loadReferences(type) {
  const referenceData = {};
  const calls = [];
  if (BRANCH_TYPES.has(type)) calls.push(['branches', () => loadCollection(api.branches.list)]);
  if (['bookings', 'quotations', 'payments', 'invoices', 'agreements'].includes(type)) {
    calls.push(['customers', () => loadCollection(api.customers.list)]);
  }
  if (['bookings', 'agreements'].includes(type)) calls.push(['workspaces', () => loadCollection(api.workspaces.list)]);
  if (['bookings', 'quotations'].includes(type)) calls.push(['inventory', () => loadCollection(api.inventory.list)]);
  if (type === 'attendance') calls.push(['users', () => loadCollection(api.users.list)]);
  const results = await Promise.all(calls.map(async ([key, call]) => [key, await call()]));
  results.forEach(([key, result]) => { referenceData[key] = result; });
  referenceData.existing = await loadExisting(type);
  return referenceData;
}

function buildRow(type, row, user, refs) {
  const fields = {};
  if (BRANCH_TYPES.has(type)) fields.branchId = resolveBranch(row, refs.branches, user);
  const required = (name, ...aliases) => {
    const result = readField(row, name, ...aliases);
    if (!result) throw new Error(`${name} is required.`);
    return result;
  };
  const number = (name, optional = false) => {
    const raw = readField(row, name);
    if (!raw && optional) return undefined;
    const parsed = Number(raw);
    if (!Number.isFinite(parsed)) throw new Error(`${name} must be a valid number.`);
    return parsed;
  };
  const customerForRow = () => {
    const email = required('customerEmail', 'customer');
    const customer = findCustomer(refs.customers, email, fields.branchId);
    if (!customer) throw new Error(`Customer "${email}" was not found in this branch.`);
    fields.customerId = recordId(customer);
  };

  switch (type) {
    case 'bookings': {
      customerForRow();
      const workspaceCode = required('workspaceCode', 'workspace', 'seat');
      const workspace = findWorkspace(refs.workspaces, fields.branchId, workspaceCode);
      if (!workspace) throw new Error(`Workspace "${workspaceCode}" was not found in this branch.`);
      fields.workspaceId = recordId(workspace);
      fields.startsAt = asDate(required('startsAt', 'startDate', 'date'), 'startsAt');
      fields.endsAt = asDate(required('endsAt', 'endDate'), 'endsAt');
      if (new Date(fields.endsAt) <= new Date(fields.startsAt)) throw new Error('endsAt must be after startsAt.');
      fields.unitRate = number('unitRate');
      fields.quantity = number('quantity', true) ?? 1;
      fields.seatCount = number('seatCount', true) ?? 1;
      fields.advanceAmount = number('advanceAmount', true) ?? 0;
      fields.status = readField(row, 'status') || 'CONFIRMED';
      fields.notes = readField(row, 'notes');
      if (fields.unitRate < 0 || fields.quantity <= 0 || fields.seatCount <= 0 || fields.advanceAmount < 0) {
        throw new Error('Rates and advance must be non-negative; quantity and seatCount must be positive.');
      }
      break;
    }
    case 'customers':
      fields.fullName = required('fullName', 'name');
      fields.email = required('email').toLowerCase();
      fields.phone = required('phone');
      fields.companyName = readField(row, 'companyName', 'company');
      fields.gstin = readField(row, 'gstin');
      fields.panNumber = readField(row, 'panNumber');
      break;
    case 'workspaces':
      fields.floor = required('floor');
      fields.code = required('code');
      fields.name = required('name');
      fields.workspaceType = readField(row, 'workspaceType', 'type') || 'PRIVATE_CABIN';
      fields.capacity = number('capacity', true) ?? 1;
      fields.status = readField(row, 'status') || 'AVAILABLE';
      if (fields.capacity <= 0) throw new Error('capacity must be a positive number.');
      break;
    case 'inventory':
      fields.name = required('name');
      fields.description = readField(row, 'description');
      fields.rate = number('rate');
      fields.unit = required('unit');
      fields.taxPercent = number('taxPercent', true) ?? 0;
      fields.productType = readField(row, 'productType') || 'WORKSPACE';
      fields.sellable = !['false', '0', 'no'].includes(lower(readField(row, 'sellable')));
      if (fields.rate < 0 || fields.taxPercent < 0 || fields.taxPercent > 100) {
        throw new Error('rate must be non-negative and taxPercent must be between 0 and 100.');
      }
      break;
    case 'quotations':
      customerForRow();
      fields.items = parseItems(required('items'), refs.inventory);
      fields.discountAmount = number('discountAmount', true) ?? 0;
      fields.taxRate = number('taxRate', true) ?? 18;
      fields.taxMode = readField(row, 'taxMode') || 'CGST_SGST';
      fields.validUntil = readField(row, 'validUntil') ? asDate(readField(row, 'validUntil'), 'validUntil', true) : '';
      fields.notes = readField(row, 'notes');
      break;
    case 'users':
      fields.fullName = required('fullName', 'name');
      fields.email = required('email').toLowerCase();
      fields.role = required('role').toUpperCase().replace(/[\s-]+/g, '_');
      if (!['SUPER_ADMIN', 'BRANCH_ADMIN', 'RECEPTION_ADMIN', 'EMPLOYEE', 'CUSTOMER'].includes(fields.role)) {
        throw new Error('role must be SUPER_ADMIN, BRANCH_ADMIN, RECEPTION_ADMIN, EMPLOYEE, or CUSTOMER.');
      }
      break;
    case 'attendance': {
      const email = required('userEmail', 'employeeEmail', 'email');
      const person = findUser(refs.users, email, fields.branchId);
      if (!person) throw new Error(`Active staff member "${email}" was not found in this branch.`);
      fields.userId = recordId(person);
      fields.workDate = asDate(required('workDate', 'date'), 'workDate', true);
      fields.checkIn = asDate(required('checkIn', 'clockIn'), 'checkIn');
      fields.checkOut = readField(row, 'checkOut', 'clockOut') ? asDate(readField(row, 'checkOut', 'clockOut'), 'checkOut') : '';
      if (fields.checkOut && new Date(fields.checkOut) < new Date(fields.checkIn)) throw new Error('checkOut must be on or after checkIn.');
      fields.notes = readField(row, 'notes');
      break;
    }
    case 'expenses':
      fields.category = required('category');
      fields.amount = number('amount');
      fields.date = asDate(required('date', 'expenseDate'), 'date', true);
      fields.vendor = readField(row, 'vendor');
      fields.status = readField(row, 'status') || 'COMPLETED';
      fields.notes = readField(row, 'notes');
      if (fields.amount < 0) throw new Error('amount must be non-negative.');
      break;
    case 'payments':
      customerForRow();
      fields.amount = number('amount');
      fields.paymentMethod = readField(row, 'paymentMethod') || 'OTHER';
      fields.dueDate = readField(row, 'dueDate') ? asDate(readField(row, 'dueDate'), 'dueDate', true) : '';
      fields.status = readField(row, 'status') || 'PENDING';
      fields.notes = readField(row, 'notes');
      if (fields.amount < 0) throw new Error('amount must be non-negative.');
      break;
    case 'invoices':
      customerForRow();
      fields.dueDate = asDate(required('dueDate'), 'dueDate', true);
      fields.totalAmount = number('totalAmount');
      fields.status = readField(row, 'status') || 'PENDING';
      fields.notes = readField(row, 'notes');
      if (fields.totalAmount < 0) throw new Error('totalAmount must be non-negative.');
      break;
    case 'agreements': {
      customerForRow();
      const workspaceCode = readField(row, 'workspaceCode', 'workspace');
      if (workspaceCode) {
        const workspace = findWorkspace(refs.workspaces, fields.branchId, workspaceCode);
        if (!workspace) throw new Error(`Workspace "${workspaceCode}" was not found in this branch.`);
        fields.workspaceId = recordId(workspace);
      }
      fields.startDate = asDate(required('startDate', 'date'), 'startDate', true);
      fields.endDate = asDate(required('endDate'), 'endDate', true);
      if (fields.endDate < fields.startDate) throw new Error('endDate must be on or after startDate.');
      fields.contractValue = number('contractValue');
      fields.depositAmount = number('depositAmount', true) ?? 0;
      fields.status = readField(row, 'status') || 'ACTIVE';
      fields.terms = readField(row, 'terms');
      if (fields.contractValue < 0 || fields.depositAmount < 0) throw new Error('Contract and deposit amounts must be non-negative.');
      break;
    }
    default:
      throw new Error('Unsupported import type.');
  }
  return fields;
}

function createRecord(type, fields) {
  switch (type) {
    case 'bookings':
      return api.bookings.create({
        ...fields,
        unitPrice: fields.unitRate,
        isExistingRecord: true,
        bookingSource: 'IN_PERSON',
      });
    case 'customers':
      return api.customers.create(fields);
    case 'workspaces':
      return api.workspaces.create(fields);
    case 'inventory':
      return api.inventory.create(fields);
    case 'quotations':
      return api.quotations.create(fields);
    case 'users':
      return api.users.create(fields);
    case 'attendance':
      return api.attendance.import(fields);
    case 'expenses':
      return api.expenses.create(fields);
    case 'payments':
      return api.payments.create(fields);
    case 'invoices':
      return api.invoices.create(fields);
    case 'agreements':
      return api.agreements.create(fields);
    default:
      throw new Error('Unsupported import type.');
  }
}

function downloadTemplate(type, format) {
  const fields = IMPORT_TYPES[type].fields;
  const worksheet = XLSX.utils.aoa_to_sheet([fields]);
  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, worksheet, IMPORT_TYPES[type].label);
  if (format === 'xlsx') {
    XLSX.writeFile(workbook, `nanospace-${type}-template.xlsx`);
    return;
  }
  const csv = `\uFEFF${fields.map((field) => `"${field.replace(/"/g, '""')}"`).join(',')}\r\n`;
  const link = document.createElement('a');
  link.href = URL.createObjectURL(new Blob([csv], { type: 'text/csv;charset=utf-8' }));
  link.download = `nanospace-${type}-template.csv`;
  link.click();
  URL.revokeObjectURL(link.href);
}

