function normalizedRow(row) {
  return Object.fromEntries(
    Object.entries(row).map(([key, value]) => [
      key.trim().toLowerCase().replace(/[\s_-]+/g, ''),
      value,
    ])
  );
}

function readField(row, ...names) {
  for (const name of names) {
    const value = row[name.toLowerCase().replace(/[\s_-]+/g, '')];
    if (value !== undefined && value !== null && String(value).trim() !== '') return String(value).trim();
  }
  return '';
}

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;

  for (let index = 0; index < text.length; index += 1) {
    const character = text[index];
    if (quoted) {
      if (character === '"' && text[index + 1] === '"') {
        field += '"';
        index += 1;
      } else if (character === '"') {
        quoted = false;
      } else {
        field += character;
      }
    } else if (character === '"' && field.length === 0) {
      quoted = true;
    } else if (character === ',') {
      row.push(field);
      field = '';
    } else if (character === '\n' || character === '\r') {
      if (character === '\r' && text[index + 1] === '\n') index += 1;
      row.push(field);
      if (row.some((cell) => String(cell).trim())) rows.push(row);
      row = [];
      field = '';
    } else {
      field += character;
    }
  }
  if (quoted) throw new Error('The CSV file contains an unclosed quoted field.');
  row.push(field);
  if (row.some((cell) => String(cell).trim())) rows.push(row);
  if (rows.length < 2) throw new Error('The file must contain a header row and at least one data row.');

  const headers = rows[0].map((header) => String(header).replace(/^\uFEFF/, '').trim());
  if (headers.some((header) => !header)) throw new Error('Every CSV column must have a header.');
  return rows.slice(1).map((cells) =>
    normalizedRow(Object.fromEntries(headers.map((header, index) => [header, cells[index] ?? ''])))
  );
}

async function readImportFile(file) {
  if (file.size > 10 * 1024 * 1024) throw new Error('Choose a file smaller than 10 MB.');
  if (file.name.toLowerCase().endsWith('.csv')) return parseCsv(await file.text());
  if (!file.name.toLowerCase().endsWith('.xlsx')) {
    throw new Error('Choose a CSV or Excel .xlsx file.');
  }

  const workbook = XLSX.read(await file.arrayBuffer(), { type: 'array', cellDates: true });
  const firstSheet = workbook.Sheets[workbook.SheetNames[0]];
  if (!firstSheet) throw new Error('The workbook does not contain a worksheet.');
  const rows = XLSX.utils.sheet_to_json(firstSheet, { defval: '', raw: false });
  if (!rows.length) throw new Error('The worksheet must contain a header row and at least one data row.');
  return rows.map(normalizedRow);
}

function value(record, ...keys) {
  for (const key of keys) {
    const field = record?.[key];
    if (field !== undefined && field !== null && String(field).trim() !== '') return String(field).trim();
  }
  return '';
}

function lower(valueToNormalize) {
  return String(valueToNormalize || '').trim().toLowerCase();
}

function asDate(valueToParse, fieldName, dateOnly = false) {
  const date = new Date(valueToParse);
  if (!valueToParse || Number.isNaN(date.getTime())) throw new Error(`${fieldName} must be a valid date or timestamp.`);
  return dateOnly ? date.toISOString().slice(0, 10) : date.toISOString();
}

function parseItems(rawItems, inventory) {
  let items;
  try {
    items = JSON.parse(rawItems);
  } catch {
    throw new Error('items must be a valid JSON array.');
  }
  if (!Array.isArray(items) || items.length === 0) throw new Error('items must contain at least one inventory item.');
  return items.map((item, index) => {
    const itemKey = value(item, 'inventoryItemId', 'itemId', 'id', 'name', 'itemName');
    const match = inventory.find((entry) =>
      lower(value(entry, 'id', 'inventory_item_id')) === lower(itemKey) ||
      lower(value(entry, 'name')) === lower(itemKey)
    );
    if (!match) throw new Error(`Quotation item ${index + 1} does not match an inventory ID or name.`);
    const quantity = Number(item.quantity ?? item.qty ?? 1);
    if (!Number.isFinite(quantity) || quantity <= 0) throw new Error(`Quotation item ${index + 1} needs a positive quantity.`);
    return { inventoryItemId: value(match, 'id', 'inventory_item_id'), quantity };
  });
}

function recordBranchId(record) {
  return value(record, 'branchId', 'branch_id');
}

function recordEmail(record) {
  return lower(value(record, 'email', 'employee_email', 'customer_email'));
}

function recordId(record) {
  return value(record, 'id', '_id');
}

function resolveBranch(row, branches, user) {
  const branchInput = readField(row, 'branch', 'branchName', 'branchId');
  const ownBranchId = value(user, 'branchId', 'branch_id');
  const ownBranch = branches.find((branch) => recordId(branch) === ownBranchId);

  if (String(user.role).toLowerCase() !== 'super_admin') {
    if (!ownBranchId) throw new Error('Your account does not have a branch assigned.');
    if (branchInput && ![ownBranchId, value(ownBranch, 'name', 'branch_name'), value(ownBranch, 'code')].some((entry) => lower(entry) === lower(branchInput))) {
      throw new Error('The row branch does not match your assigned branch.');
    }
    return ownBranchId;
  }

  if (!branchInput) throw new Error('Branch is required for Super Admin imports.');
  const branch = branches.find((entry) =>
    [recordId(entry), value(entry, 'name', 'branch_name'), value(entry, 'code')]
      .some((candidate) => lower(candidate) === lower(branchInput))
  );
  if (!branch) throw new Error(`Branch "${branchInput}" was not found. Use its name, code, or ID.`);
  return recordId(branch);
}

function findCustomer(customers, email, branchId) {
  return customers.find((customer) =>
    recordEmail(customer) === lower(email) && recordBranchId(customer) === branchId
  );
}

function findWorkspace(workspaces, branchId, code) {
  return workspaces.find((workspace) =>
    recordBranchId(workspace) === branchId &&
    [value(workspace, 'code'), value(workspace, 'name'), recordId(workspace)]
      .some((candidate) => lower(candidate) === lower(code))
  );
}

function findUser(users, email, branchId) {
  return users.find((entry) =>
    recordEmail(entry) === lower(email) &&
    recordBranchId(entry) === branchId &&
    entry.is_active !== false &&
    entry.is_active !== 0
  );
}

